// Builds standalone HTML pages from the design-canvas source.
// Usage: node scripts/build.mjs   (no dependencies needed)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'canvas-source/Prototype.dc.html'), 'utf8');

const tpl = src.match(/<x-dc>([\s\S]*?)<\/x-dc>/)[1];
const scriptTag = src.match(/<script type="text\/x-dc"([^>]*)>([\s\S]*?)<\/script>/);
const propsAttr = (scriptTag[1].match(/data-props='([^']*)'/) || [])[1] || '{}';
const logic = scriptTag[2];

const pages = [
  { file: 'index.html', screen: 'Home', title: 'Levotrade · Full flow' },
  { file: 'home.html', screen: 'Home', title: 'Home' },
  { file: 'proforma-invoice.html', screen: 'Proforma Invoice', title: 'Proforma Invoice' },
  { file: 'pi-detail.html', screen: 'PI Detail', title: 'PI Details' },
  { file: 'complete-pi.html', screen: 'Complete PI (pre-filled)', title: 'Complete PI' },
  { file: 'add-pi.html', screen: 'Add PI', title: 'Add PI' },
  { file: 'add-pi-products.html', screen: 'Add PI · products added', title: 'Add PI · products added' },
  { file: 'add-pi-popup.html', screen: 'Add PI · product pop-up', title: 'Add PI · product pop-up' },
  { file: 'edit-pi.html', screen: 'Edit PI', title: 'Edit PI' },
];

for (const p of pages) {
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${p.title} · Levotrade</title>
<!-- Generated by scripts/build.mjs from canvas-source/Prototype.dc.html — do not edit by hand -->
<link rel="stylesheet" href="ds/levotrade/tokens.css">
<link rel="stylesheet" href="ds/levotrade/components/bundle.css">
<script src="vendor/react.production.min.js"></script>
<script src="vendor/react-dom.production.min.js"></script>
<script src="ds/levotrade/components/bundle.js"></script>
<script src="runtime/levo-runtime.js"></script>
</head>
<body>
<div id="root"></div>
<template id="dc-template">${tpl}</template>
<script type="text/plain" id="dc-logic" data-props='${propsAttr}'>${logic}</script>
<script>LevoRuntime.mount({ props: { startScreen: ${JSON.stringify(p.screen)} } });</script>
</body>
</html>
`;
  writeFileSync(join(root, p.file), html);
  console.log('built', p.file);
}
